// Returns an animal profile deterministically based on player name or index
export function getAnimalForParticipant(name: string, index: number): AnimalProfile {
  let hash = 0;
  const clean = name.trim().toLowerCase();
  for (let i = 0; i < clean.length; i++) {
    hash = (hash * 31 + clean.charCodeAt(i)) >>> 0;
  }
  const pickedIndex = (hash + index) % ANIMAL_PROFILES.length;
  return ANIMAL_PROFILES[pickedIndex];
}
